const test = require("node:test");
const assert = require("node:assert/strict");
const { loadGame, trace } = require("./game-harness.cjs");

test("Restart level in Pause resets the attempt without changing campaign progress or loadout", () => {
  const saved = new Map([["doodle-defense-v3", JSON.stringify({ unlocked: 2, wins: { 1: true }, stars: { 1: 3 } })]]);
  const { game, document } = loadGame(undefined, { saved, boot: true });
  const starting = game.start({ level: 2, diff: "hard", loadout: ["decoy"], routeSeed: 17 });
  const before = game.save();
  const byId = id => document.getElementById(id);
  assert.ok(trace(game, "red", [95, 145], [220, 145]));
  assert.ok(game.place("decoy", 65, 250));
  assert.ok(game.startWave());
  game.advance(3.1);
  assert.ok(game.state().monsters.length);
  byId("btn-pause").click();
  assert.equal(byId("modal-pause").classList.contains("on"), true);
  assert.equal(byId("btn-restart").textContent, "Restart level");
  byId("btn-restart").click();
  const restarted = game.state();
  assert.equal(byId("modal-pause").classList.contains("on"), false);
  assert.equal(restarted.id, starting.id);
  assert.equal(restarted.phase, "plan");
  assert.equal(restarted.waveIdx, 0);
  assert.equal(restarted.t, 0);
  assert.equal(restarted.ink, starting.ink);
  assert.equal(restarted.house.hp, starting.house.hp);
  assert.equal(restarted.diff, "hard");
  assert.deepEqual(restarted.loadout, starting.loadout);
  for (const list of [restarted.strokes, restarted.comps, restarted.monsters, restarted.incoming]) assert.equal(list.length, 0);
  assert.deepEqual(game.save(), before);
  assert.ok(game.startWave());
  game.advance(1);
  assert.ok(game.state().t > 0);
});

test("the restart control also works in Endless and on the results screen", () => {
  const { game, document } = loadGame(undefined, { boot: true });
  const byId = id => document.getElementById(id);
  game.startEndless({ diff: "easy", loadout: [] });
  game.advance(7);
  assert.ok(game.state().wave > 0);
  byId("btn-pause").click();
  assert.equal(byId("btn-restart").textContent, "Restart run");
  byId("btn-restart").click();
  const run = game.state();
  assert.equal(run.endless, true);
  assert.equal(run.diff, "easy");
  assert.equal(run.loadout.length, 0);
  assert.equal(run.wave, 0);
  game.start({ level: 2, houseHp: 1 });
  assert.ok(game.startWave());
  game.advance(60);
  assert.equal(game.state().ended, "lose");
  assert.equal(byId("btn-again").textContent, "Restart level");
  byId("btn-again").click();
  assert.equal(byId("modal-end").classList.contains("on"), false);
  assert.equal(game.state().ended, null);
  assert.equal(game.state().phase, "plan");
});
